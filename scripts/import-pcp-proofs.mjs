import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';

// Pin the source so re-running this import preserves problem IDs and solutions.
const revision = 'b0c27507646a4f0acfee555948b5d09d26c5e6cc';
const instances = [
  '1110_1__1_0__0_1110',
  '1101_1__1_101__0_011',
  '1001_1__10_0__0_100',
  '1101_1__1_10__0_1011',
  '1110_0__10_1__1_1011',
];

const entries = await Promise.all(instances.map(async (instance, index) => {
  const source = `https://github.com/Mojashi/pcp-3-4-proofs/blob/${revision}/proofs/${instance}/solvable.thy`;
  const response = await fetch(source.replace('github.com', 'raw.githubusercontent.com').replace('/blob/', '/'));
  assert.ok(response.ok, `Failed to fetch ${source}: ${response.status}`);
  const theory = await response.text();
  const match = theory.match(/definition solution_\d+::"nat list" where "solution_\d+ \\<equiv>\s*\[([\d,\s]+)\]/);
  assert.ok(match, `Missing solution in ${source}`);
  const witness = match[1].split(',').map(value => Number(value.trim()));
  const pairs = instance.split('__').map(pair => pair.split('_'));
  const declaredPairs = [...theory.matchAll(/\(\[([C01,]+)\],\[([C01,]+)\]\)/g)]
    .map(match => [match[1].replaceAll('C', '').replaceAll(',', ''), match[2].replaceAll('C', '').replaceAll(',', '')]);
  assert.deepEqual(declaredPairs, pairs);
  assert.ok(witness.length > 1 && witness.every(tile => Number.isInteger(tile) && tile >= 0 && tile < pairs.length));
  assert.equal(witness.map(tile => pairs[tile][0]).join(''), witness.map(tile => pairs[tile][1]).join(''));

  // Equal binary symbols must become complementary sushi/flower pairs.
  const encode = (word, bottom = false) => [...word].map(bit => (bit === '0') !== bottom ? 'S' : 'T').join('');
  const tiles = pairs.map(([top, bottom], tile) => ({
    id: `tile-${tile + 1}`, top: encode(top), bottom: encode(bottom, true),
  }));
  // Seed the board with the first move to avoid an empty board clearing itself.
  const first = tiles[witness[0]];
  let common = 0;
  while (common < Math.min(first.top.length, first.bottom.length) && first.top[common] !== first.bottom[common]) common++;
  const initialState = { topBelt: first.top.slice(common), bottomBelt: first.bottom.slice(common) };
  assert.ok(initialState.topBelt.length + initialState.bottomBelt.length > 0);
  const problem = { id: String(13 + index), difficulty: 'np-hard', solvable: true, initialState, tiles, solution: witness.slice(1) };
  console.log(`Problem ${problem.id}: ${instance}, witness ${witness.length}, playable moves ${problem.solution.length}`);
  const formatted = JSON.stringify(problem, null, 2).replace(/"solution": \[\s*([\d,\s]+)\]/, (_, values) => `"solution": [${values.replace(/\s+/g, ' ').trim()}]`);
  return `  // ${source}\n  ${formatted.replaceAll('\n', '\n  ')}`;
}));

await writeFile(new URL('../src/data/discoveredProblems.ts', import.meta.url),
  `// Generated by node scripts/import-pcp-proofs.mjs.\nimport type { Problem } from '../types';\n\nexport const discoveredProblems: Problem[] = [\n${entries.join(',\n')}\n];\n`);
